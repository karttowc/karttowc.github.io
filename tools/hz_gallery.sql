-- 헬멧 갤러리 (v1.8.18-d3). Supabase SQL Editor에 붙여 넣고 Run, 한 번만.
-- 원하는 사람만 올림. 자동 숨김 없음: 신고는 reports 칸에 쌓기만 하고, logs.py '점검'에서 보고 찬우가 지운다.
--   지우기: delete from hz_gallery where id = 123;
create table if not exists public.hz_gallery (
  id bigint generated by default as identity primary key,
  name text not null check (length(name) between 1 and 24),
  dz text not null check (length(dz) <= 3000 and dz ~ '^~[.a-x0-9]+$'),
  b text not null check (b ~ '^#[0-9A-Fa-f]{6}$'),
  lg text check (lg is null or length(lg) <= 40),
  lx real check (lx is null or (lx >= 0 and lx <= 1)),
  ly real check (ly is null or (ly >= 0 and ly <= 1)),
  ls real check (ls is null or (ls >= 0 and ls <= 1)),
  reports integer not null default 0,
  del_hash text check (del_hash is null or length(del_hash) = 64),
  created_at timestamptz not null default now()
);
alter table public.hz_gallery enable row level security;

-- 게임(anon)은 보기·올리기만. 신고 수·삭제 열쇠 해시는 안 보임
revoke all on public.hz_gallery from anon;
grant select (id, name, dz, b, lg, lx, ly, ls, created_at) on public.hz_gallery to anon;
grant insert (name, dz, b, lg, lx, ly, ls, del_hash) on public.hz_gallery to anon;
grant usage on sequence public.hz_gallery_id_seq to anon;
drop policy if exists hzg_read on public.hz_gallery;
create policy hzg_read on public.hz_gallery for select to anon using (true);
drop policy if exists hzg_add on public.hz_gallery;
create policy hzg_add on public.hz_gallery for insert to anon with check (reports = 0);

-- 도배 막기: 전체 1시간에 120개까지
create or replace function public.hzg_limit() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if (select count(*) from hz_gallery where created_at > now() - interval '1 hour') >= 120 then
    raise exception 'hz_gallery: too many uploads';
  end if;
  new.reports := 0;
  return new;
end $$;
drop trigger if exists hzg_limit on public.hz_gallery;
create trigger hzg_limit before insert on public.hz_gallery for each row execute function public.hzg_limit();

-- 신고: 수만 올림(숨기지 않음)
create or replace function public.hz_report(p_id bigint)
returns integer language plpgsql security definer set search_path = public as $$
declare n integer;
begin
  update hz_gallery set reports = reports + 1 where id = p_id;
  get diagnostics n = row_count;
  return n;
end $$;
grant execute on function public.hz_report(bigint) to anon;

-- 올린 사람 지우기: 폰에 있는 삭제 열쇠가 맞으면
create or replace function public.hz_delete(p_id bigint, p_key text)
returns integer language plpgsql security definer set search_path = public as $$
declare n integer;
begin
  delete from hz_gallery where id = p_id and del_hash = encode(sha256(convert_to(p_key, 'UTF8')), 'hex');
  get diagnostics n = row_count;
  return n;
end $$;
grant execute on function public.hz_delete(bigint, text) to anon;

-- 신고 들어온 헬멧 목록(logs.py 점검용)
create or replace function public.hz_reported()
returns table (id bigint, name text, dz text, b text, reports integer, created_at timestamptz)
language sql security definer set search_path = public as $$
  select id, name, dz, b, reports, created_at from hz_gallery where reports > 0 order by id;
$$;
grant execute on function public.hz_reported() to anon;
